export type AppErrorCode = typeof APP_ERROR_CODES[keyof typeof APP_ERROR_CODES];

const visibleCode = /\(Код:\s*[A-Z][A-Z0-9_]{2,63}\)$/;
const stableCode = /^[A-Z][A-Z0-9_]{2,63}$/;

/** Presentation only. Never append arbitrary server messages or private values as support codes. */
export function withErrorCode(message: string, code: string): string {
  if (visibleCode.test(message)) return message;
  return message + ' (Код: ' + (stableCode.test(code) ? code : 'UNKNOWN_ERROR') + ')';
}
